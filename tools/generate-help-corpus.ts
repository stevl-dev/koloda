import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Writes the assistant's help corpus: `docs/decisions/SPECS-AS-ASSISTANT-HELP.md`.

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));

const SOURCE_DIRS = ["docs/specs", "docs/help"];

export const HELP_CORPUS_PATH = "libs/ai/src/lib/help-corpus.generated.ts";

type Section = { heading: string; depth: 2 | 3; markdown: string };

export type SourceTopic = {
  id: string;
  path: string;
  title: string;
  summary: string;
  intro: string;
  sections: Section[];
};

function firstSentence(path: string, paragraph: string): string {
  const text = paragraph.split("\n").join(" ").trim();
  const match = /^(.+?\.)(?:\s|$)/.exec(text);
  if (!match) throw new Error(`${path}: no first sentence to use as the topic summary`);
  return match[1];
}

function firstParagraph(lines: string[]): string {
  const start = lines.findIndex((line) => line.trim() !== "");
  if (start === -1) return "";
  const end = lines.findIndex((line, index) => index > start && line.trim() === "");
  return lines.slice(start, end === -1 ? undefined : end).join("\n");
}

function parseTopic(path: string): SourceTopic {
  const markdown = readFileSync(join(root, path), "utf8");
  // INVARIANT: the chunks join back into the source exactly; `readHelpTopic` rebuilds whole topics from them.
  const chunks = markdown.split(/^(?=#{2,3} )/m);
  const intro = chunks[0];
  const sections = chunks.slice(1).map((chunk): Section => {
    const heading = chunk.split("\n")[0];
    const depth = heading.startsWith("### ") ? 3 : 2;
    return { heading: heading.slice(depth + 1).trim(), depth, markdown: chunk };
  });

  const introLines = intro.split("\n");
  const titleLine = introLines.find((line) => line.startsWith("# "));
  if (!titleLine) throw new Error(`${path}: no "# " title`);
  const isSpec = path.startsWith("docs/specs/");
  const scope = sections.find((section) => section.depth === 2 && section.heading === "Scope");
  if (isSpec && !scope) throw new Error(`${path}: no Scope section`);
  const summarySource = isSpec
    ? firstParagraph(scope?.markdown.split("\n").slice(1) ?? [])
    : firstParagraph(introLines.slice(introLines.indexOf(titleLine) + 1));

  const name = path.split("/").pop() ?? path;
  return {
    id: name.replace(/\.md$/, "").toLowerCase(),
    path,
    title: titleLine.slice(2).trim(),
    summary: firstSentence(path, summarySource),
    intro,
    sections,
  };
}

export function readHelpSources(): SourceTopic[] {
  const paths = SOURCE_DIRS.flatMap((dir) =>
    readdirSync(join(root, dir))
      .filter((name) => name.endsWith(".md"))
      .map((name) => `${dir}/${name}`),
  );
  const topics = paths.map(parseTopic).sort((a, b) => a.id.localeCompare(b.id));
  const duplicate = topics.find((topic, index) => topics[index + 1]?.id === topic.id);
  if (duplicate) throw new Error(`two help sources share the topic id "${duplicate.id}"`);
  return topics;
}

export function renderHelpCorpus(topics: SourceTopic[]): string {
  const body = topics.map(({ id, title, summary, intro, sections }) => ({ id, title, summary, intro, sections }));
  return [
    "// Generated by `bun run gen:help` from `docs/specs/` and `docs/help/`. Do not edit.",
    'import type { HelpTopic } from "./help-corpus";',
    "",
    `export const HELP_TOPIC_IDS = ${JSON.stringify(topics.map((topic) => topic.id))} as const;`,
    "",
    `export const HELP_TOPICS: HelpTopic[] = ${JSON.stringify(body, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(join(root, HELP_CORPUS_PATH), renderHelpCorpus(readHelpSources()));
}
